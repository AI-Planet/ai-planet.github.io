/* =========================================
   Translate the menu and text elements marked with data-i18n
   ========================================= */

const languageSelector = document.getElementById("language-selector");

/* Map each menu link to its translation key */
const menuKeys = {
    "academy.html": "academy",
    "kyokushin.html": "kyokushin",
    "sensei.html": "sensei",
    "gallery.html": "gallery",
    "news.html": "news",
    "contact.html": "contact",
    "fighters.html": "fighters"
};

/* Apply the selected language to the page */
function changeLanguage(language) {
    const words = translations[language];

    if (!words) return;

    /* Translate the navigation links */
    document.querySelectorAll("nav a").forEach(link => {
        const key = menuKeys[link.getAttribute("href")];

        if (key && words[key]) {
            link.textContent = words[key];
        }
    });

    /* Translate all elements with the data-i18n attribute */
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");

        if (words[key]) {
            element.innerHTML = words[key];
        }
    });

    /* Update the HTML language attribute for browsers */
    document.documentElement.lang = language;
}

/* Apply translations when the language selection changes */
if (languageSelector) {
    languageSelector.addEventListener("change", function () {
        changeLanguage(this.value);
    });
}
